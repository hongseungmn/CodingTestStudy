package 코딩테스트고득점Kit.동적계획법;

public class 멀리뛰기 {
  /*
    효진이는 한번에 1칸, 또는 2칸을 뛸 수 있습니다. 칸이 총 4개 있을 때, 효진이는
    (1칸, 1칸, 1칸, 1칸)
    (1칸, 2칸, 1칸)
    (1칸, 1칸, 2칸)
    (2칸, 1칸, 1칸)
    (2칸, 2칸)
    의 5가지 방법으로 맨 끝 칸에 도달
  
    효진이가 끝에 도달하는 방법

    cf) 1칸을 이동하는 방법 f(1) = 1; (1)
        2칸을 이동하는 방법 f(2) = 2; (1, 1), (2)                                                                                               -> f(1) + 새로운 방법(1) 
        3칸을 이동하는 방법 f(3) = 3; (1, 1, 1), (1, 2), (2, 1)                                                                                 -> f(1) + 새로운 방법(2)
        4칸을 이동하는 방법 f(4) = 5; (1, 1, 1, 1), (1, 2, 1), (1, 1, 2), (2, 1, 1), (2, 2)                                                     -> f(3) + f(2)
        5칸을 이동하는 방법 f(5) = 8; (1, 1, 1, 1, 1), (1, 1, 1, 2), (1, 1, 2, 1), (1, 2, 1, 1), (1, 2, 2), (2, 1, 1, 1), (2, 1, 2), (2, 2, 1)  -> f(4) + f(3)

        ... f(n) = f(n-1) + f(n-2)
  */

  static int[] DP = new int[2001]; 
  public long solution(int n) {
    
    DP[1] = 1;
    DP[2] = 2;
    DP[3] = 3;
    if(n < 4) return DP[n];
    for(int i=4;i<=n; i++) {
      DP[i] = (DP[i-1] + DP[i-2]) % 1234567;
    }

    return DP[n];
  }
}
